import logging
import uuid

from odoo import api, fields, models

_logger = logging.getLogger(__name__)


class SyncMixin(models.AbstractModel):
    _name = "sync.mixin"
    _description = "Synchronization Mixin"

    sync_uuid = fields.Char(
        string="Sync UUID",
        copy=False,
        readonly=True,
        index=True,
    )

    # ------------------------------------------------------------------
    # ORM hooks
    # ------------------------------------------------------------------
    def _sync_is_disabled(self):
        """No job is queued for writes done by the configuration fetch
        (`sync_in_progress`) or by the sync code itself (`skip_sync`)."""
        ctx = self.env.context
        return bool(ctx.get("skip_sync") or ctx.get("sync_in_progress"))

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get("sync_uuid"):
                vals["sync_uuid"] = str(uuid.uuid4())

        records = super().create(vals_list)

        if not self._sync_is_disabled():
            records._create_sync_queue("create")

        return records

    def write(self, vals):
        result = super().write(vals)

        if not self._sync_is_disabled():
            self._create_sync_queue("update")

        return result

    def unlink(self):
        if not self._sync_is_disabled():
            self._create_sync_queue("delete")

        return super().unlink()

    def _create_sync_queue(self, operation, priority=10):
        SyncQueue = self.env["sync.queue"].sudo()

        for record in self:
            if not record.sync_uuid:
                record.with_context(skip_sync=True).write({"sync_uuid": str(uuid.uuid4())})

            job = SyncQueue.enqueue(
                model_name=record._name,
                record_id=record.id,
                sync_uuid=record.sync_uuid,
                operation=operation,
                priority=priority,
            )
            _logger.debug(
                "[SYNC] queue request model=%s id=%s op=%s -> job %s",
                record._name, record.id, operation, job.id if job else None,
            )

    # ------------------------------------------------------------------
    # Payload
    # ------------------------------------------------------------------
    @api.model
    def _sync_get_connection(self):
        return self.env["sync.connection"].sudo().search([("active", "=", True)], limit=1)

    def _sync_prepare_values(self, connection=None):
        self.ensure_one()
        connection = connection or self._sync_get_connection()

        values = {}

        fields_to_skip = {
            "id",
            "create_uid",
            "create_date",
            "write_uid",
            "write_date",
            "__last_update",
            "sync_uuid",
            # local hierarchy data, meaningless (and harmful) on the remote
            "parent_path",
            "message_main_attachment_id",
        }

        for field_name, field in self._fields.items():

            if field_name in fields_to_skip:
                continue

            # Computed fields are normally generated by the remote Odoo itself.
            if field.compute or not field.store:
                continue

            if field.type in ("binary", "html"):
                continue

            # one2many are pushed from the child side (their many2one points back)
            if field.type == "one2many":
                continue

            value = self[field_name]

            if field.type == "many2one":
                if not value:
                    values[field_name] = False
                    continue
                key = self._sync_get_relation_key(field_name, connection=connection)
                if key:
                    values[field_name] = key
                else:
                    _logger.debug(
                        "[SYNC] %s.%s -> %s(%s) has no remote reference, skipped",
                        self._name, field_name, value._name, value.id,
                    )

            elif field.type == "many2many":
                keys = []
                for record in value:
                    key = self._sync_get_relation_key(field_name, record, connection)
                    if key:
                        keys.append(key)
                values[field_name] = keys

            elif field.type == "date":
                values[field_name] = fields.Date.to_string(value) if value else False

            elif field.type == "datetime":
                values[field_name] = fields.Datetime.to_string(value) if value else False

            elif field.type in (
                "char",
                "text",
                "selection",
                "boolean",
                "integer",
                "float",
                "monetary",
            ):
                values[field_name] = value

        return values

    def _sync_get_relation_key(self, field_name, record=None, connection=None):
        """Describe a related record so the remote can find it.

        The key carries every hint available (the remote resolves them in this order):
          - remote_id: from sync.record.map (record fetched from / pushed to the remote)
          - xmlid:     standard data that exists on both sides (countries, companies...)
          - sync_uuid: record handled by the push registry

        Returns False when the record cannot be identified on the remote at all."""
        if record is None:
            record = self[field_name]

        if not record:
            return False

        connection = connection or self._sync_get_connection()
        key = {"model": record._name}

        remote_id = False
        if connection:
            remote_id = (
                self.env["sync.record.map"].sudo()._get_remote_id(connection, record._name, record.id)
            )
        if remote_id:
            key["remote_id"] = remote_id

        xmlid = record.get_external_id().get(record.id)
        if xmlid and not xmlid.startswith("__export__."):
            key["xmlid"] = xmlid

        if "sync_uuid" in record._fields:
            if not record.sync_uuid:
                record.with_context(skip_sync=True).write({"sync_uuid": str(uuid.uuid4())})
            key["sync_uuid"] = record.sync_uuid
            if not remote_id and "xmlid" not in key:
                self._sync_ensure_dependency_queued(record)

        if len(key) == 1:
            return False
        return key

    def _sync_ensure_dependency_queued(self, record):
        """The related record is neither on the remote nor in the queue yet: queue it
        with a higher priority, the job that needs it is retried by the queue."""
        if not getattr(record, "_sync_enabled", False):
            return
        Queue = self.env["sync.queue"].sudo()
        if Queue.search_count(
            [
                ("model_name", "=", record._name),
                ("record_id", "=", record.id),
                ("state", "in", ("pending", "processing", "done")),
            ]
        ):
            return
        record._create_sync_queue("create", priority=20)
