import logging
import uuid

from odoo import api, fields, models

_logger = logging.getLogger(__name__)


class SyncMixin(models.AbstractModel):
    """Push the records created locally to the remote Odoo (local -> remote).

    Inherit it together with the model to synchronize (see res_partner.py).

    * every new record gets a `sync_uuid` and a job in `sync.queue`;
    * the job is processed by the queue cron, which sends the record to the remote
      (`sync.registry.apply`) and stores the id the record received there
      (`sync.record.map`);
    * relational fields are translated to remote ids when the payload is built
      (see `_sync_get_relation_key`).
    """

    _name = "sync.mixin"
    _description = "Synchronization Mixin"

    # Operations pushed to the remote. A model can narrow this down by overriding the
    # attribute, e.g. _sync_operations = ("create",) for a model whose later edits or
    # deletions must stay local.
    _sync_operations = ("create", "update", "delete")

    # Never sent to the remote.
    _sync_skipped_fields = frozenset({
        "id",
        "create_uid",
        "create_date",
        "write_uid",
        "write_date",
        "__last_update",
        "sync_uuid",
        # local hierarchy data, meaningless (and harmful) on the remote
        "parent_path",
        "message_main_attachment_id",
    })

    # Field types that are sent. Read-only computed fields are left to the remote (it
    # computes them itself), one2many are pushed from the child side (their many2one
    # points back), binary / html are not supported yet.
    _sync_field_types = (
        "char", "text", "selection", "boolean", "integer", "float", "monetary",
        "date", "datetime", "many2one", "many2many",
    )

    sync_uuid = fields.Char(
        string="Sync UUID",
        copy=False,
        readonly=True,
        index=True,
    )

    # ------------------------------------------------------------------
    # ORM hooks
    # ------------------------------------------------------------------
    def _sync_is_disabled(self):
        """`skip_sync` is set by the sync code itself (e.g. the remote applying a
        pushed record) so that its own writes are never queued."""
        return bool(self.env.context.get("skip_sync"))

    def _sync_should_queue(self, operation):
        return operation in self._sync_operations and not self._sync_is_disabled()

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get("sync_uuid"):
                vals["sync_uuid"] = str(uuid.uuid4())

        records = super().create(vals_list)

        if self._sync_should_queue("create"):
            records._create_sync_queue("create")

        return records

    def write(self, vals):
        result = super().write(vals)

        # Only a change of a field that is actually pushed is worth a job (writes to
        # computed or technical fields would just resend an identical record).
        if self._sync_should_queue("update") and any(
            self._sync_is_syncable_field(field_name) for field_name in vals
        ):
            self._create_sync_queue("update")

        return result

    def unlink(self):
        # Queued before the deletion: the job needs the id and the sync_uuid.
        if self._sync_should_queue("delete"):
            self._create_sync_queue("delete")

        return super().unlink()

    def _create_sync_queue(self, operation, priority=10):
        SyncQueue = self.env["sync.queue"].sudo()

        for record in self:
            # Records that came with the imported database have no uuid yet.
            if not record.sync_uuid:
                record.with_context(skip_sync=True).write({"sync_uuid": str(uuid.uuid4())})

            job = SyncQueue.enqueue(
                model_name=record._name,
                record_id=record.id,
                sync_uuid=record.sync_uuid,
                operation=operation,
                priority=priority,
            )
            _logger.debug(
                "[SYNC] queue request model=%s id=%s op=%s -> job %s",
                record._name, record.id, operation, job.id if job else None,
            )

    # ------------------------------------------------------------------
    # Payload
    # ------------------------------------------------------------------
    @api.model
    def _sync_get_connection(self):
        return self.env["sync.connection"].sudo().search([("active", "=", True)], limit=1)

    @api.model
    def _sync_is_syncable_field(self, field_name):
        """Is this field part of the payload sent to the remote?"""
        field = self._fields.get(field_name)
        if field is None or field_name in self._sync_skipped_fields:
            return False
        if not field.store:
            return False
        # A computed field the user cannot edit is generated by the remote Odoo itself.
        # A computed field the user CAN edit (compute + store + readonly=False, e.g.
        # payment_term_id, pricelist_id, partner_invoice_id on sale.order) holds a
        # choice made by the user: it has to be sent, otherwise the remote would
        # compute its own value and ignore the one chosen locally.
        if (field.compute or field.related) and field.readonly:
            return False
        return field.type in self._sync_field_types

    def _sync_prepare_values(self, connection=None):
        """Build the values sent to the remote. Relational values are replaced by
        relation keys (see `_sync_get_relation_key`) that the remote resolves."""
        self.ensure_one()
        connection = connection or self._sync_get_connection()

        values = {}

        for field_name, field in self._fields.items():

            if not self._sync_is_syncable_field(field_name):
                continue

            value = self[field_name]

            if field.type == "many2one":
                if not value:
                    values[field_name] = False
                    continue
                key = self._sync_get_relation_key(field_name, connection=connection)
                if key:
                    values[field_name] = key
                else:
                    _logger.warning(
                        "[SYNC] %s.%s -> %s(%s) cannot be identified on the remote, skipped",
                        self._name, field_name, value._name, value.id,
                    )

            elif field.type == "many2many":
                keys = []
                for record in value:
                    key = self._sync_get_relation_key(field_name, record, connection)
                    if key:
                        keys.append(key)
                    else:
                        _logger.warning(
                            "[SYNC] %s.%s -> %s(%s) cannot be identified on the remote, skipped",
                            self._name, field_name, record._name, record.id,
                        )
                values[field_name] = keys

            elif field.type == "date":
                values[field_name] = fields.Date.to_string(value) if value else False

            elif field.type == "datetime":
                values[field_name] = fields.Datetime.to_string(value) if value else False

            elif field.type in (
                "char",
                "text",
                "selection",
                "boolean",
                "integer",
                "float",
                "monetary",
            ):
                values[field_name] = value

        return values

    def _sync_get_relation_key(self, field_name, record=None, connection=None):
        """Describe a related record so the remote can find it.

        The hints are tried in this order (the remote resolves them in the same
        order, see `sync.registry._resolve_relation_key`):

          1. remote_id - the id of the record on the remote. Taken from
                         sync.record.map (record created locally and already pushed)
                         or equal to the local id (record that came with the
                         imported database). When it is known nothing else is sent.
          2. xmlid     - standard data present on both sides, e.g. created by a
                         module installed after the import.
          3. sync_uuid - record created locally that is not on the remote yet. It is
                         queued with a higher priority and the job that needs it is
                         retried until it has been pushed.

        Returns False when the record cannot be identified on the remote at all."""
        if record is None:
            record = self[field_name]

        if not record:
            return False

        connection = connection or self._sync_get_connection()

        # 1. id on the remote
        remote_id = False
        if connection:
            remote_id = (
                self.env["sync.record.map"].sudo()._get_remote_id(connection, record._name, record.id)
            )
        if remote_id:
            return {"model": record._name, "remote_id": remote_id}

        key = {"model": record._name}

        # 2. xmlid of standard data
        xmlid = record.get_external_id().get(record.id)
        if xmlid and not xmlid.startswith("__export__."):
            key["xmlid"] = xmlid

        # 3. sync_uuid of a record that still has to be pushed
        if "sync_uuid" in record._fields:
            if not record.sync_uuid:
                record.with_context(skip_sync=True).write({"sync_uuid": str(uuid.uuid4())})
            key["sync_uuid"] = record.sync_uuid
            if "xmlid" not in key:
                self._sync_ensure_dependency_queued(record)

        if len(key) == 1:
            return False
        return key

    def _sync_ensure_dependency_queued(self, record):
        """The related record is neither on the remote nor in the queue yet: queue it
        with a higher priority, the job that needs it is retried by the queue."""
        if not getattr(record, "_sync_enabled", False):
            return
        Queue = self.env["sync.queue"].sudo()
        if Queue.search_count(
            [
                ("model_name", "=", record._name),
                ("record_id", "=", record.id),
                ("state", "in", ("pending", "processing", "done")),
            ]
        ):
            return
        record._create_sync_queue("create", priority=20)
