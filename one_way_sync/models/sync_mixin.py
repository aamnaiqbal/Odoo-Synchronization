import uuid
import logging
from odoo import api, fields, models, _
from odoo.exceptions import UserError


_logger = logging.getLogger(__name__)


class SyncMixin(models.AbstractModel):
    _name = "sync.mixin"
    _description = "Synchronization Mixin"

    sync_uuid = fields.Char(
        string="Sync UUID",
        copy=False,
        readonly=True,
        index=True,
    )

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get("sync_uuid"):
                vals["sync_uuid"] = str(uuid.uuid4())

        records = super().create(vals_list)

        if not self.env.context.get("skip_sync"):
            records._create_sync_queue("create")

        

        return records

    def write(self, vals):
        result = super().write(vals)

        if not self.env.context.get("skip_sync"):
            self._create_sync_queue("update")

        return result

    def unlink(self):
        if not self.env.context.get("skip_sync"):
            self._create_sync_queue("delete")

        return super().unlink()

    def _create_sync_queue(self, operation):
        _logger.warning(
            "========== QUEUE REQUEST: model=%s id=%s uuid=%s operation=%s ==========",
            self._name,
            self.id,
            self.sync_uuid,
            operation,
        )
        SyncQueue = self.env["sync.queue"].sudo()

        for record in self:
            if not record.sync_uuid:
                record.with_context(skip_sync=True).write({
                    "sync_uuid": str(uuid.uuid4()),
                })

            job = SyncQueue.enqueue(
                model_name=record._name,
                record_id=record.id,
                sync_uuid=record.sync_uuid,
                operation=operation,
            )

            _logger.warning(
                "========== QUEUE RESULT: id=%s operation=%s ==========",
                job.id if job else None,
                job.operation if job else None,
            )

    def _sync_prepare_values(self):
        self.ensure_one()

        values = {}

        fields_to_skip = {
            "id",
            "create_uid",
            "create_date",
            "write_uid",
            "write_date",
            "__last_update",
            "sync_uuid",
        }

        for field_name, field in self._fields.items():

            if field_name in fields_to_skip:
                continue

            # Computed fields are normally generated by the
            # remote Odoo itself.
            if field.compute:
                continue

            if field.type in (
                "binary",
                "html",
            ):
                continue

              # ---------------------------------------------------------
            # TEMPORARY:
            # Skip ALL relational fields
            # ---------------------------------------------------------
            if field.type in (
                "many2one",
                "many2many",
                "one2many",
            ):
                continue

            value = self[field_name]

            if field.type in (
                "char",
                "text",
                "selection",
                "boolean",
                "integer",
                "float",
                "monetary",
                "date",
                "datetime",
            ):
                values[field_name] = value

            # elif field.type == "many2one":
            #     values[field_name] = (
            #         self._sync_get_relation_key(
            #             field_name
            #         )
            #         if value
            #         else False
            #     )

            # elif field.type in (
            #     "many2many",
            #     "one2many",
            # ):
            #     values[field_name] = [
            #         self._sync_get_relation_key(field_name, record)
            #         for record in value
            #     ]

        return values

    def _sync_get_relation_key(
        self,
        field_name,
        record=None,
    ):
        field = self._fields[field_name]

        if record is None:
            record = self[field_name]

        if not record:
            return False

        if "sync_uuid" in record._fields:
            if not record.sync_uuid:
                record.with_context(skip_sync=True).write({
                    "sync_uuid": str(uuid.uuid4()),
                })

            return {
                "model": record._name,
                "sync_uuid": record.sync_uuid,
            }

        return {
            "model": record._name,
            "id": record.id,
        }